"""Regenerate the numbers in README sections that come from results files (explainability, reviewer fixes).

    python scripts/write_readme_results.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
pc = lambda x: f"{100 * x:.1f}%"  # noqa: E731


def explain_block() -> str:
    r = json.loads((ROOT / "results/explainability.json").read_text())
    d, m = r["synthetic"]["deletion"], r["macro"]
    att = r["synthetic"]["attribution_by_typology"]
    lo = min(att, key=lambda k: att[k]["mean"])
    return f'''<!-- EXPLAIN:START (generated by scripts/write_readme_results.py) -->
### What "explainable" means here, and how it is measured

**Definition.** An alert is explainable when it lists the specific evidence that produced it (the values, the benchmark and the rule) **and** removing that evidence removes the alert. Kashf's score is built from the evidence (noisy-OR), so this can be tested directly. Numbers from `results/explainability.md` (`python -m kashf.explain_eval`):

- **Evidence attribution (synthetic):** for every planted typology, at least {pc(att[lo]['mean'])} of true alerts cite a rule that matches the planted mechanism (lowest: {lo}). This is partly by construction (the detectors were written for these typologies), so it shows the evidence is *about the right thing*, not that the detectors generalise.
- **Deletion test (synthetic, {d['all_alerts']['alerts']:,} alerts on 5 held-out seeds):** dropping an alert's strongest signal removes the alert in {pc(d['all_alerts']['drop_top_removes_alert'])} of cases, against {pc(d['all_alerts']['drop_random_removes_alert'])} for dropping a random signal. For alerts with two or more signals: {pc(d['multi_signal_alerts']['drop_top_removes_alert'])} vs {pc(d['multi_signal_alerts']['drop_random_removes_alert'])}; the rest survive because a second, independent signal also crosses the threshold (redundant evidence). Removing all cited evidence removes every alert.
- **Macro layer (real UN Comtrade):** for the {m['pairs_flagged_by_both']} pairs flagged by both the rules and the Isolation Forest, SHAP's top feature belongs to a rule that fired in {pc(m['shap_top1_in_fired_rule'])} of cases (random: {pc(m['random_top1_expected'])}).
- **Not yet measured:** whether the evidence makes analysts faster or more accurate. `docs/user_study.md` is a protocol with an empty results table; no study has been run.
<!-- EXPLAIN:END -->'''


def synthetic_block() -> str:
    sm = json.loads((ROOT / "results/summary.json").read_text())
    rob = json.loads((ROOT / "results/robustness.json").read_text())
    rr = json.loads((ROOT / "results/real_reference/summary.json").read_text())
    C = sm["configs"]
    n_typ = len(C["kashf_full"]["recall_by_typology"])
    rate = sum(c["laundering"] / c["invoices"] for c in sm["counts"]) / len(sm["counts"])
    f3 = lambda c, k: f"{C[c][k]['mean']:.3f}"  # noqa: E731
    rows = [("**Kashf (calibrated)**", "kashf_full"), ("Kashf (hand-set weights)", "kashf_heuristic"),
            ("Kashf, exact identifier matching only", "exact_entities"), ("Kashf without route detector", "minus_route"),
            ("Price benchmark only", "price_only"),
            ("IQR price filter (de Boyrie, Pak & Zdanowicz)", "iqr_price_filter"),
            ("Isolation forest", "isolation_forest"), ("Manual-review checklist", "checklist")]
    T = "\n".join(f"| {lab} | {f3(c, 'precision')} | {f3(c, 'recall')} | {f3(c, 'f1')} | {100 * C[c]['far']['mean']:.2f}% | "
                  f"{f3(c, 'avg_precision')} |" for lab, c in rows)
    rt = {k: v["mean"] for k, v in C["kashf_full"]["recall_by_typology"].items()}
    ex = {k: v["mean"] for k, v in C["exact_entities"]["recall_by_typology"].items()}
    mr = {k: v["mean"] for k, v in C["minus_route"]["recall_by_typology"].items()}
    sh = rob["shift"]
    sw = {n: [v["f1"]["mean"] for v in vals.values()] for n, vals in rob["sweep"].items()}
    at = rob["alert_threshold"]
    route_gain = C["kashf_full"]["f1"]["mean"] - C["minus_route"]["f1"]["mean"]
    curve = {b["bin"]: b["recall"] for b in sm["mispricing_recall"]}
    return f'''<!-- SYNTH:START (generated by scripts/write_readme_results.py) -->
## Synthetic benchmark (invoice layer)

Evaluation on the synthetic UAE trade benchmark: about {100 * rate:.1f}% of invoices are laundering across {n_typ} typologies (including transshipment through FATF-listed jurisdictions, U-turn trade and name-variant shell networks). Thresholds and calibration were tuned on seed 0; results are the mean over {len(sm["counts"])} held-out seeds of {sm["protocol"]["invoices_per_seed"]:,} invoices each. Full tables: [`results/results.md`](results/results.md).

| Configuration | Precision | Recall | F1 | False-alarm rate | Avg. precision |
|---|---|---|---|---|---|
{T}

<p><img src="results/figures/f1_by_config.png" width="49%"> <img src="results/figures/recall_by_typology.png" width="49%"></p>

What the numbers say:
- **Combining detectors matters most.** Without the document or graph detector F1 falls to {f3("minus_documents", "f1")} and {f3("minus_graph", "f1")}.
- **The route detector now earns its place.** With route typologies in the benchmark it adds {route_gain:.3f} F1 (recall on transshipment {mr["transshipment_high_risk"]:.2f} → {rt["transshipment_high_risk"]:.2f}, U-turn {mr["u_turn"]:.2f} → {rt["u_turn"]:.2f}), above the 0.01 bar for keeping it in the score. U-turn recall stays low because genuine returns of goods look the same.
- **Fuzzy entity resolution matters for disguised shells.** Recall on name-variant shell networks is {ex["name_variant"]:.2f} with exact identifier matching and {rt["name_variant"]:.2f} with normalised phones/addresses and rapidfuzz name matching.
- **Moderate mispricing is the hard case.** Recall is {curve.get("1.5-2x", 0):.0%} for prices pushed 1.5–2× from the benchmark, {curve.get("3-4x", 0):.0%} at 3–4× and {curve.get(">10x", 0):.0%} beyond 10×. The published IQR price filter flags {100 * C["iqr_price_filter"]["far"]["mean"]:.0f}% of clean invoices by construction.

> Synthetic data generated by the same author who wrote the detectors: these results show the method works, not how it would perform on real trade.

### Robustness checks (synthetic)

From [`results/robustness.md`](results/robustness.md), tuned on seed 0 and tested on seeds 1–3:

| Check | F1 | False-alarm rate |
|---|---|---|
| Default thresholds, same generator (seeds 1–3; the main table uses seeds 1–5) | {sh["same_generator"]["f1"]["mean"]:.3f} | {100 * sh["same_generator"]["far"]["mean"]:.2f}% |
| Hand-set thresholds swept one at a time | {min(min(v) for v in sw.values()):.3f}–{max(max(v) for v in sw.values()):.3f} | |
| Alert threshold {min(at, key=float)} → {max(at, key=float)} (calibration fixed) | {min(v["f1"]["mean"] for v in at.values()):.3f}–{max(v["f1"]["mean"] for v in at.values()):.3f} | |
| **Generator shift** (more noise, subtler mispricing) | **{sh["shifted_generator"]["f1"]["mean"]:.3f}** | **{100 * sh["shifted_generator"]["far"]["mean"]:.2f}%** |
| **Different typology mechanics** (longer, slower rings; bank-linked shells; split multiple invoicing; subtler mispricing) | **{sh["alt_typologies"]["f1"]["mean"]:.3f}** | **{100 * sh["alt_typologies"]["far"]["mean"]:.2f}%** |

Under different typology mechanics, over- and under-invoicing recall falls to {sh["alt_typologies"]["recall_by_typology"]["over_invoicing"]:.2f} and {sh["alt_typologies"]["recall_by_typology"]["under_invoicing"]:.2f} and circular trading to {sh["alt_typologies"]["recall_by_typology"]["circular_trading"]:.2f}: calibration must be refitted per data source. With **real UN Comtrade reference prices** the same benchmark gives F1 {rr["configs"]["kashf_full"]["f1"]["mean"]:.3f} ([`results/real_reference/results.md`](results/real_reference/results.md)).
<!-- SYNTH:END -->
'''


def checks_block() -> str:
    ext, aml, cases = (json.loads((ROOT / f).read_text()) for f in
                       ("results/external_validation.json", "results/amlworld.json", "results/public_cases.json"))
    vis = [v for v in cases.values() if v["expect"] == "evidence"]
    k, g = ext["methods"]["kashf_rules"], ext["methods"]["gfi_gap"]
    a = aml["methods"]["kashf_cycle_adapted"]["all"]
    t = aml["methods"]["timefree_cycle_3to5"]
    return f'''<!-- CHECKS:START (generated by scripts/write_readme_results.py) -->
## External and independent checks

Summary of all reviewer fixes, with every number's source: [`results/reviewer_fixes.md`](results/reviewer_fixes.md).

- **Published gold flows (real data, not laundering labels).** SWISSAID reports name {ext["documented_keys"]} UAE gold flows as mismatched or as smuggling transit routes (`data/external_validation.csv`, with sources and pages). {ext["documented_keys_in_data"]} exist as mirror pairs. Kashf's rules flag {k["keys_flagged_by_kind"].get("mirror_discrepancy", 0)}/{ext["by_kind"]["mirror_discrepancy"]["in_data"]} documented mismatches and {k["keys_flagged_by_kind"].get("transit_hub", 0)}/{ext["by_kind"]["transit_hub"]["in_data"]} transit flows, but rank them mid-table (median rank {k["median_best_rank"]:.0f} of {ext["eligible_pairs"]:,}); a GFI-style dollar gap ranks them far higher (median {g["median_best_rank"]:.0f}). [`results/external_validation.md`](results/external_validation.md)
- **IBM AMLworld (independent synthetic data).** Only the circular-trade rule applies. As shipped it finds {100 * aml["methods"]["kashf_cycle_as_shipped"]["recall_by_typology"]["cycle"]:.0f}% of cycle-pattern transfers; adapted to transfer data (timestamps, USD amounts, up to 10 hops; not tuned on labels) it finds {100 * aml["methods"]["kashf_cycle_adapted"]["recall_by_typology"]["cycle"]:.0f}% at precision {a["precision"]:.2f}, against {100 * t["recall_by_typology"]["cycle"]:.0f}% at precision {t["all"]["precision"]:.2f} for a time-free cycle check. Overall recall is {100 * a["recall"]:.1f}% because most AMLworld laundering is not cyclic. [`results/amlworld.md`](results/amlworld.md). To reproduce, download `HI-Small_Trans.csv` and `HI-Small_Patterns.txt` from the [Kaggle dataset](https://www.kaggle.com/datasets/ealtman2019/ibm-transactions-for-anti-money-laundering-aml) (not redistributed here) and run `python -m kashf.amlworld --trans HI-Small_Trans.csv --patterns HI-Small_Patterns.txt`.
- **Public FATF/Egmont cases (reconstructed).** Evidence surfaces in {sum(set(v["rules_expected"]) <= set(v["rules_fired"]) for v in vis)}/{len(vis)} schemes visible in trade records; only {sum(v["alerts"] > 0 for v in vis)}/{len(vis)} crosses the alert threshold. Payment-side schemes are blind spots. [`results/public_cases.md`](results/public_cases.md)
- **Published baselines.** On injected real distortions an IQR price filter matches or beats Kashf's rules at the same flag rate for ×2–×5 distortions; Kashf is ahead at ×10. [`results/macro/injection_summary.csv`](results/macro/injection_summary.csv)
<!-- CHECKS:END -->
'''


def main() -> None:
    p = ROOT / "README.md"
    s = p.read_text()
    blk = explain_block()
    if "<!-- EXPLAIN:START" in s:
        s = re.sub(r"<!-- EXPLAIN:START.*?<!-- EXPLAIN:END -->", lambda _: blk, s, flags=re.S)
    else:
        s = re.sub(r'### What "explainable" means here, and how it is measured\n.*?no study has been run\.\n',
                   lambda _: blk + "\n", s, flags=re.S)
    sb = synthetic_block()
    if "<!-- SYNTH:START" in s:
        s = re.sub(r"<!-- SYNTH:START.*?<!-- SYNTH:END -->\n", lambda _: sb, s, flags=re.S)
    else:
        s = re.sub(r"## Synthetic benchmark \(invoice layer\)\n.*?(?=## Real data: macro layer)", lambda _: sb + "\n", s, flags=re.S)
    cb = checks_block()
    if "<!-- CHECKS:START" in s:
        s = re.sub(r"<!-- CHECKS:START.*?<!-- CHECKS:END -->\n", lambda _: cb, s, flags=re.S)
    else:
        s = s.replace("## Quick start", cb + "\n## Quick start", 1)
    p.write_text(s)
    print("README updated")


if __name__ == "__main__":
    main()
