#!/usr/bin/env bash
# Run the real-data pipeline, check it, fill README + PITCH_NOTES, commit, push and open the PR.
# Run from the repo root on branch real-data-layer, with .venv active and COMTRADE_KEY in .env.
#
#   bash scripts/finish_on_mac.sh
set -euo pipefail
cd "$(dirname "$0")/.."

say() { printf '\n== %s\n' "$*"; }
die() { printf '\nSTOP: %s\n' "$*" >&2; exit 1; }

[ "$(git branch --show-current)" = "real-data-layer" ] || die "switch to branch real-data-layer first"
git check-ignore -q .env || die ".env is not gitignored"
git check-ignore -q data/raw/x.parquet || die "data/raw/ is not gitignored"
[ -f .env ] || die "create .env with COMTRADE_KEY=<your key>"

say "Part 1: real data (UN Comtrade)"
bash scripts/run_real.sh

say "Sanity check"
python scripts/sanity_check.py || die "sanity check failed; read the FAIL lines above and send them to Claude"

say "Tests"
python -m pytest -q

say "README real-data section + PITCH_NOTES.md (numbers copied from results files)"
python scripts/write_notes.py

say "Stage only derived outputs"
git add README.md PITCH_NOTES.md docs/DATA_CARD.md data/reference_comtrade.csv data/reference_comtrade_detail.csv \
        results/macro results/real_reference 2>/dev/null || true
git status --short
STAGED="$(git diff --cached --name-only)"
if echo "$STAGED" | grep -qE '(^|/)\.env$|^data/raw/'; then
  git reset -q
  die ".env or data/raw/ was staged; unstaged everything, nothing committed"
fi
KEY="$(sed -n 's/^COMTRADE_KEY=//p' .env | tr -d '[:space:]')"
[ -n "$KEY" ] || die "COMTRADE_KEY is empty in .env"
if [ -n "$STAGED" ] && echo "$STAGED" | xargs grep -lsF -- "$KEY" >/dev/null 2>&1; then
  git reset -q
  die "the API key text appears in a staged file; nothing committed"
fi

say "Commit and push"
git commit -m "Add real UN Comtrade results, data card and pitch notes" -m "Numbers generated by scripts/run_real.sh and copied by scripts/write_notes.py."
git push -u origin real-data-layer

say "Pull request"
if command -v gh >/dev/null && gh auth status >/dev/null 2>&1; then
  gh pr create --base main --head real-data-layer --title "Real-data layer (UN Comtrade), macro detector, Render deploy" \
    --body "Adds the UN Comtrade data layer, mirror-gap macro detector with real-data results, robustness checks, and a free Render deployment (render.yaml). See README and PITCH_NOTES.md."
else
  echo "gh not available or not logged in. Open: https://github.com/lilanayele/kashf/compare/main...real-data-layer"
fi
