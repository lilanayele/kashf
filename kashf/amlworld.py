"""Independent benchmark: Kashf's counterparty-graph detectors on IBM AMLworld (HI-Small).

Dataset: E. Altman et al., "Realistic Synthetic Financial Transactions for Anti-Money Laundering
Models", NeurIPS 2023 Datasets & Benchmarks (arXiv:2306.16424); files HI-Small_Trans.csv and
HI-Small_Patterns.txt from https://www.kaggle.com/datasets/ealtman2019/ibm-transactions-for-anti-money-laundering-aml
(not redistributed here; download them yourself). It was generated by IBM, not by Kashf's author.

Mapping (what transfers and what does not):
  * account (bank id + account id)  -> entity. No names, directors, phones, addresses: the shared-
    identifier part of the graph detector cannot fire, so only the circular-trade rule is tested.
  * transfer payer -> payee          -> a trade in which value passes from payer to payee
    (seller = payer, buyer = payee), so a chain of transfers forward in time maps to goods moving forward
    along a chain of companies, which is what the circular-trade rule follows; date = transfer day,
    quantity = amount paid, "HS code" = payment currency, so only amounts in the same currency are compared. Self-transfers (payer = payee) are kept and scored
    like any transfer, but no rule can fire on them.
  * Two runs of Kashf's rule: "as shipped" (calendar-day dates, goods = currency, raw amounts) and
    "adapted" (timestamps so same-day hops keep their order, amounts converted to USD at the dataset's
    own median cross-currency rates, cycles up to 10 hops as AMLworld's pattern file states; same
    10% amount tolerance and 60-day hop window). Neither was tuned on the labels.
  * NOT transferred: HS codes, unit prices, documents and routes, so the price, document and route
    detectors are not evaluated, and laundering patterns other than cycles (fan-in/out, scatter-gather,
    bipartite, stack, random) are outside what the cycle rule looks for.
Labels: the dataset's "Is Laundering" flag per transfer; typology from HI-Small_Patterns.txt.

Baselines (simple, no learning): fan-out / fan-in degree rules (payer sends to >= k distinct payees,
or payee receives from >= k distinct payers, within the dataset) with k chosen on the first half of
days, and a time-free cycle check (transfer lies on a directed cycle of 3-5 accounts, ignoring
amounts and dates).

    python -m kashf.amlworld --trans HI-Small_Trans.csv --patterns HI-Small_Patterns.txt
"""

from __future__ import annotations

import argparse
import json
import logging
import time
from dataclasses import replace
from pathlib import Path

import numpy as np
import pandas as pd

from kashf.config import Settings

log = logging.getLogger("kashf.amlworld")
COLS = ["ts", "from_bank", "from_acct", "to_bank", "to_acct", "amt_recv", "cur_recv", "amt_paid", "cur_paid",
        "fmt", "y"]


def load(trans: Path, patterns: Path) -> pd.DataFrame:
    df = pd.read_parquet(trans) if str(trans).endswith(".parquet") else pd.read_csv(trans, dtype=str)
    df.columns = COLS
    df = df.astype({"amt_paid": float, "amt_recv": float, "y": int})
    typ = {}
    cur = None
    for line in Path(patterns).read_text().splitlines():
        if line.startswith("BEGIN LAUNDERING ATTEMPT"):
            cur = line.split("-", 1)[1].split(":")[0].strip().lower().replace("-", "_")
        elif line.startswith("END LAUNDERING ATTEMPT"):
            cur = None
        elif cur and line.strip():
            p = line.split(",")
            typ[(p[0], p[2], p[4], f"{float(p[7]):.2f}")] = cur
    key = list(zip(df["ts"], df["from_acct"], df["to_acct"], df["amt_paid"].map(lambda v: f"{v:.2f}")))
    df["typology"] = [typ.get(k, "none") for k in key]
    df.loc[(df["y"] == 1) & (df["typology"] == "none"), "typology"] = "unlisted"
    return df


def usd_rates(df: pd.DataFrame) -> dict[str, float]:
    """USD per unit of each currency, from the dataset's own cross-currency transfers (median ratio)."""
    rates = {"US Dollar": 1.0}
    x = df[(df["cur_paid"] == "US Dollar") & (df["cur_recv"] != "US Dollar")]
    for c, g in x.groupby("cur_recv"):
        rates[c] = float(np.median(g["amt_paid"] / g["amt_recv"]))
    x = df[(df["cur_recv"] == "US Dollar") & (df["cur_paid"] != "US Dollar")]
    for c, g in x.groupby("cur_paid"):
        rates.setdefault(c, float(np.median(g["amt_recv"] / g["amt_paid"])))
    return rates


def to_invoices(df: pd.DataFrame, adapted: bool = False) -> pd.DataFrame:
    """adapted=False: invoice semantics as shipped (calendar day, goods = currency, raw amounts).
    adapted=True: transfer semantics (timestamp, all currencies in USD at the dataset's own median rates,
    one goods class), still with Kashf's rule and tolerances."""
    a = df["from_bank"].astype(str) + ":" + df["from_acct"].astype(str)
    b = df["to_bank"].astype(str) + ":" + df["to_acct"].astype(str)
    if adapted:
        r = usd_rates(df)
        date = pd.to_datetime(df["ts"]).astype(str)
        hs, q = "ALL", df["amt_paid"] * df["cur_paid"].map(r).fillna(np.nan)
    else:
        date = pd.to_datetime(df["ts"]).dt.date.astype(str)
        hs, q = df["cur_paid"].values, df["amt_paid"]
    return pd.DataFrame({"invoice_no": np.arange(len(df)).astype(str), "date": np.asarray(date), "seller_id": a.values,
                         "buyer_id": b.values, "hs6": hs, "quantity": np.asarray(q)})


def kashf_cycles(inv: pd.DataFrame, s: Settings) -> np.ndarray:
    from kashf.detectors import _cycles

    sig = _cycles(inv[inv["seller_id"] != inv["buyer_id"]], s)
    hit = {x.invoice_no for x in sig}
    return inv["invoice_no"].isin(hit).to_numpy()


def degree_scores(df: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]:
    out_deg = df.groupby("from_acct")["to_acct"].nunique()
    in_deg = df.groupby("to_acct")["from_acct"].nunique()
    return df["from_acct"].map(out_deg).to_numpy(), df["to_acct"].map(in_deg).to_numpy()


def timefree_cycles(df: pd.DataFrame, max_len: int = 5) -> np.ndarray:
    """Transfer u->v lies on a directed cycle of 3..max_len accounts (amounts and dates ignored)."""
    import networkx as nx

    e = df.loc[df["from_acct"] != df["to_acct"], ["from_acct", "to_acct"]].drop_duplicates()
    g = nx.DiGraph()
    g.add_edges_from(e.itertuples(index=False, name=None))
    on = set()
    for c in nx.simple_cycles(g, length_bound=max_len):
        if len(c) >= 3:
            for i in range(len(c)):
                on.add((c[i], c[(i + 1) % len(c)]))
    return np.array([(u, v) in on for u, v in zip(df["from_acct"], df["to_acct"])])


def prf(flag: np.ndarray, y: np.ndarray) -> dict:
    tp, fp, fn = int((flag & y).sum()), int((flag & ~y).sum()), int((~flag & y).sum())
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    return {"precision": p, "recall": r, "f1": 2 * p * r / (p + r) if p + r else 0.0, "flagged": int(flag.sum()),
            "tp": tp}


def run(trans: Path, patterns: Path, out: Path, max_expansions: int = 50_000_000) -> dict:
    t0 = time.time()
    df = load(trans, patterns)
    y = df["y"].to_numpy().astype(bool)
    days = pd.to_datetime(df["ts"]).dt.normalize()
    split = days.min() + (days.max() - days.min()) / 2
    tune, test = (days <= split).to_numpy(), (days > split).to_numpy()
    s = replace(Settings.from_yaml(), cycle_max_expansions=max_expansions)
    log.info("%d transfers, %d laundering; running Kashf cycle rule", len(df), int(y.sum()))
    flags = {"kashf_cycle_as_shipped": kashf_cycles(to_invoices(df), s)}
    log.info("cycle rule (as shipped) done in %.0fs", time.time() - t0)
    s10 = replace(s, cycle_max_len=10)        # AMLworld's pattern file states cycles of up to 10 hops
    flags["kashf_cycle_adapted"] = kashf_cycles(to_invoices(df, adapted=True), s10)
    log.info("cycle rule (adapted) done in %.0fs", time.time() - t0)
    out_d, in_d = degree_scores(df)
    for name, sc in (("fan_out_degree", out_d), ("fan_in_degree", in_d)):
        best = max(range(2, 60), key=lambda k: prf(sc[tune] >= k, y[tune])["f1"])
        flags[f"{name}_k{best}"] = sc >= best
    flags["timefree_cycle_3to5"] = timefree_cycles(df)
    log.info("baselines done in %.0fs", time.time() - t0)
    typs = sorted(t for t in df["typology"].unique() if t != "none")
    res = {"label": "IBM AMLworld HI-Small (independent synthetic data, Altman et al. 2023)",
           "transfers": int(len(df)), "laundering": int(y.sum()),
           "laundering_by_typology": {t: int((df["typology"] == t).sum()) for t in typs},
           "split_day": str(split.date()), "settings": {"cycle_max_len": s.cycle_max_len, "cycle_hop_days": s.cycle_hop_days,
                                                         "cycle_qty_tolerance": s.cycle_qty_tolerance,
                                                         "cycle_max_expansions": max_expansions},
           "methods": {}}
    for name, f in flags.items():
        res["methods"][name] = {"all": prf(f, y), "test_half": prf(f[test], y[test]),
                                "recall_by_typology": {t: float(f[(df["typology"] == t).to_numpy()].mean()) for t in typs}}
    rng = np.random.default_rng(0)
    k = int(flags["kashf_cycle_adapted"].sum())
    rnd = np.zeros(len(df), dtype=bool)
    if k:
        rnd[rng.choice(len(df), k, replace=False)] = True
    res["methods"]["random_same_count"] = {"all": prf(rnd, y), "test_half": prf(rnd[test], y[test]),
                                           "recall_by_typology": {t: float(rnd[(df["typology"] == t).to_numpy()].mean()) for t in typs}}
    out.mkdir(parents=True, exist_ok=True)
    (out / "amlworld.json").write_text(json.dumps(res, indent=2))
    write_md(res, out / "amlworld.md")
    return res


def write_md(r: dict, path: Path) -> None:
    typs = list(r["laundering_by_typology"])
    L = ["# Independent benchmark: IBM AMLworld HI-Small", "",
         "Synthetic data generated by IBM (Altman et al., NeurIPS 2023 Datasets & Benchmarks), not by Kashf's author. "
         "Only Kashf's circular-trade rule can be tested (no HS codes, prices, documents, routes or company "
         "identifiers); see kashf/amlworld.py for the mapping.", "",
         f"Transfers: {r['transfers']:,}; laundering: {r['laundering']:,} "
         f"({', '.join(f'{t} {n}' for t, n in r['laundering_by_typology'].items())}).", "",
         "| Method | Flagged | Precision | Recall | F1 | Test-half F1 |", "|---|---|---|---|---|---|"]
    for n, m in r["methods"].items():
        a = m["all"]
        L.append(f"| {n} | {a['flagged']:,} | {a['precision']:.3f} | {a['recall']:.3f} | {a['f1']:.3f} | {m['test_half']['f1']:.3f} |")
    L += ["", "Degree baselines choose k on the first half of days (up to " + r["split_day"] + "); the cycle rules have no "
          "tuned parameter (Kashf uses configs/default.yaml).", "",
          "## Recall by laundering pattern", "", "| Method | " + " | ".join(typs) + " |", "|---|" + "---|" * len(typs)]
    for n, m in r["methods"].items():
        L.append(f"| {n} | " + " | ".join(f"{m['recall_by_typology'][t]:.2f}" for t in typs) + " |")
    path.write_text("\n".join(L) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Kashf graph detectors on IBM AMLworld")
    ap.add_argument("--trans", required=True)
    ap.add_argument("--patterns", required=True)
    ap.add_argument("--out", default="results")
    ap.add_argument("--max-expansions", type=int, default=50_000_000)
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    run(Path(a.trans), Path(a.patterns), Path(a.out), a.max_expansions)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
