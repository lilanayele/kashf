"""Draft case summaries for a compliance officer.

The summary is generated only from the evidence the detectors produced — no free
text is invented. It is a draft: the officer decides whether to escalate and
whether a suspicious transaction report is warranted.
"""

from __future__ import annotations

import datetime as dt
import html

import pandas as pd

from kashf.pipeline import Result

DETECTOR_NAMES = {"price": "Price benchmark", "route": "Route check",
                  "documents": "Document consistency", "graph": "Counterparty network"}


def _ent(ents: pd.DataFrame, eid: str) -> str:
    r = ents.loc[ents["entity_id"] == eid]
    if r.empty:
        return eid
    r = r.iloc[0]
    return f"{r['name']} ({eid}, {r['kind'].replace('_', ' ')}, {r['country']})"


def invoice_case(res: Result, invoice_no: str) -> str:
    """Markdown case summary for one invoice."""
    inv = res.tables["invoices"].set_index("invoice_no").loc[invoice_no]
    sc = res.invoices.set_index("invoice_no").loc[invoice_no]
    sig = res.signals[res.signals["invoice_no"] == invoice_no].sort_values("strength", ascending=False)
    ents = res.tables["entities"]
    level = "High" if sc["score"] >= 0.8 else "Elevated" if sc["alert"] else "Low"
    lines = [
        f"# Case summary — {invoice_no}",
        "",
        f"*Draft generated by Kashf on {dt.date.today().isoformat()} for analyst review. Not a determination of wrongdoing.*",
        "",
        f"**Risk:** {level} (score {sc['score']:.2f}; alert threshold applies)",
        "",
        "## Transaction",
        "",
        "| Field | Value |", "|---|---|",
        f"| Date | {inv['date']} |",
        f"| Seller | {_ent(ents, inv['seller_id'])} |",
        f"| Buyer | {_ent(ents, inv['buyer_id'])} |",
        f"| Goods | HS {inv['hs6']} — {inv['description']} |",
        f"| Quantity | {inv['quantity']:,} {inv['unit']} |",
        f"| Unit price | ${inv['unit_price_usd']:,.2f} |",
        f"| Invoice value | ${inv['value_usd']:,.2f} |",
        f"| Route | {inv['route']} |",
        f"| Transport document | {inv['doc_no'] if isinstance(inv['doc_no'], str) else 'none on file'} |",
        "",
        "## Red flags found",
        "",
    ]
    if sig.empty:
        lines.append("No red flags.")
    for _, r in sig.iterrows():
        lines.append(f"- **{DETECTOR_NAMES[r['detector']]} — {r['rule'].replace('_', ' ')}** "
                     f"(weight {r['strength']:.2f}): {r['evidence']}")
    lines += ["", "## Suggested next steps for the analyst", ""]
    rules = set(sig["rule"])
    steps = []
    if rules & {"over_priced", "under_priced", "implausible_unit_weight"}:
        steps.append("Request the purchase order, price quotation and product specification; confirm the goods match the HS code.")
    if rules & {"no_transport_doc", "implausible_dates", "unknown_vessel", "weight_mismatch", "quantity_mismatch"}:
        steps.append("Verify shipment with the carrier or port records (vessel, voyage, container numbers, customs declaration).")
    if "doc_reused" in rules:
        steps.append("Compare all invoices citing the same transport document; establish which, if any, reflects the real sale.")
    if rules & {"linked_parties", "linked_cluster"}:
        steps.append("Obtain ownership and control information for both parties; check whether the relationship was disclosed.")
    if "circular_trade" in rules:
        steps.append("Trace the goods and payments around the loop; ask each party for the commercial reason for resale.")
    if rules & {"high_risk_party", "high_risk_transit", "route_loop", "excess_legs"}:
        steps.append("Apply enhanced due diligence for the jurisdictions on the route and document the commercial rationale.")
    steps.append("Record the outcome. If suspicion remains after review, escalate to the MLRO for a decision on filing an STR via goAML.")
    lines += [f"{i}. {s}" for i, s in enumerate(steps, 1)]
    return "\n".join(lines) + "\n"


def entity_case(res: Result, entity_id: str, max_rows: int = 15) -> str:
    e = res.entities.set_index("entity_id").loc[entity_id]
    inv = res.invoices
    mine = inv[(inv["seller_id"] == entity_id) | (inv["buyer_id"] == entity_id)].sort_values("score", ascending=False)
    lines = [f"# Counterparty summary — {e['name']} ({entity_id})", "",
             f"*Draft generated by Kashf on {dt.date.today().isoformat()} for analyst review.*", "",
             f"- Type: {e['kind'].replace('_', ' ')}, {e['country']}",
             f"- Invoices: {int(e['invoices'])}, of which alerts: {int(e['alerts'])} "
             f"(alert value ${e['alert_value_usd']:,.0f})", "",
             "| Invoice | Date | Counterparty | Goods | Value | Score | Main reason |", "|---|---|---|---|---|---|---|"]
    for _, r in mine.head(max_rows).iterrows():
        other = r["buyer_id"] if r["seller_id"] == entity_id else r["seller_id"]
        lines.append(f"| {r['invoice_no']} | {r['date']} | {other} | {r['description']} | ${r['value_usd']:,.0f} | "
                     f"{r['score']:.2f} | {str(r['top_reason'])[:90].replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def to_html(markdown_text: str) -> str:
    """Minimal, dependency-free Markdown → HTML for exports."""
    out, in_table, in_list, in_ol = [], False, False, False
    for line in markdown_text.splitlines():
        esc = html.escape(line)
        esc = _inline(esc)
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if set("".join(cells)) <= set("-: "):
                continue
            if not in_table:
                out.append("<table>")
                in_table = True
                out.append("<tr>" + "".join(f"<th>{_inline(html.escape(c))}</th>" for c in cells) + "</tr>")
            else:
                out.append("<tr>" + "".join(f"<td>{_inline(html.escape(c))}</td>" for c in cells) + "</tr>")
            continue
        if in_table:
            out.append("</table>")
            in_table = False
        if line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{esc[2:]}</li>")
            continue
        if in_list:
            out.append("</ul>")
            in_list = False
        if line[:3].rstrip(".").isdigit() and ". " in line[:4]:
            if not in_ol:
                out.append("<ol>")
                in_ol = True
            out.append(f"<li>{esc.split('. ', 1)[1]}</li>")
            continue
        if in_ol:
            out.append("</ol>")
            in_ol = False
        if line.startswith("# "):
            out.append(f"<h1>{esc[2:]}</h1>")
        elif line.startswith("## "):
            out.append(f"<h2>{esc[3:]}</h2>")
        elif line.strip():
            out.append(f"<p>{esc}</p>")
    for flag, tag in ((in_table, "</table>"), (in_list, "</ul>"), (in_ol, "</ol>")):
        if flag:
            out.append(tag)
    return "\n".join(out)


def _inline(s: str) -> str:
    import re
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    return re.sub(r"\*(.+?)\*", r"<em>\1</em>", s)
